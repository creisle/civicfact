def diff_claims(curr_claim: dict, true_claim: dict):
    """
    Generate a series of suggested revisions for the current claim compared to the expected/true claim
    """
    # check the columns match
    return DeepDiff(curr_claim, true_claim, ignore_order=True, ignore_string_case=True)


def has_revisions(row: dict):
    return isinstance(row['revisions'], dict) and len(row['revisions']) > 0


def revised_field(row: dict, field: str):
    if not has_revisions(row):
        return False
    return any([(field in key) for key in row['revisions'].get('values_changed', {}).keys()])


