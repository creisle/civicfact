def get_standardized_case_terms(df):
    """
    Normalize casing where possible so that the model does not learn to infer based on casing
    """
    all_terms = set()

    for _, row in df.drop_duplicates(['claim.flat']).iterrows():
        for col, val in row['claim']['content'].items():
            if col in ['evidenceType', 'evidenceDirection']:
                val = val.upper()
            elif col == 'molecularProfile':
                m = re.search(r'\S*EXPRESSION', val)
                if m:
                    val = val.replace(m.group(0), m.group(0).lower())

                for word in ['mutation', 'inactivating', 'loss', 'increased', 'reduced', 'fusion']:
                    val = re.sub(r'\b' + word + r'\b', word, val, flags=re.IGNORECASE)

            if isinstance(val, list):
                all_terms.update(val)
            else:
                all_terms.add(val)

    logging.info(f'There are {len(all_terms)} terms amongst the claims')

    term_case_mapping = {}
    for term in sorted(all_terms):
        term = term.strip()
        std_term = term.lower()
        term_case_mapping.setdefault(std_term, term)

        prev_term = term_case_mapping[std_term]

        if prev_term > term:
            term_case_mapping[std_term] = term

    logging.info(f'There are {len(term_case_mapping)} standardized terms')

    return term_case_mapping


def recase_claim(claim, std_term_mapping: dict):
    claim_content = claim['content']
    for col, val in claim_content.items():
        if isinstance(val, list):
            val = [std_term_mapping[item.lower().strip()] for item in val]
        else:
            val = std_term_mapping[val.lower().strip()]
        claim_content[col] = val
    claim['content'] = claim_content
    return claim


def normalize_text(text):
    return str(text).lower().replace('-', ' ')


def diff_dicts(dict1, dict2):
    if set(dict1) != set(dict2):
        return f'keys errors: {set(dict1) ^ set(dict2)}'

    value_diffs = []
    for key in dict1:
        if str(dict1[key]).lower() != str(dict2[key]).lower():
            value_diffs.append(f'{key}: {dict1[key]} vs {dict2[key]}')
    if not value_diffs:
        return 'OK'
    return 'value errors:' + '; '.join(value_diffs)


def drop_matched_sections(dict1, dict2):
    drop_keys = []
    for col in set(dict1) & set(dict2):
        if normalize_text(dict1[col]) == normalize_text(dict2[col]):
            drop_keys.append(col)
    return {c: v for c, v in dict1.items() if c not in drop_keys}, {
        c: v for c, v in dict2.items() if c not in drop_keys
    }


def compare_revision(row):
    gold_claim = json.loads(normalize_text(row['claim.flat']))
    if not row['revised_claim.flat']:
        gold_revision = {**gold_claim}
    else:
        gold_revision = json.loads(normalize_text(row['revised_claim.flat']))

    gold_claim, gold_revision = drop_matched_sections(gold_claim, gold_revision)

    original_fields = len(set(gold_claim) | set(gold_revision))
    if original_fields == 0:
        return None

    fields = (set(gold_claim) | set(gold_revision)) - {
        'therapyInteractionType',
        'variantOrigin',
        'evidenceDirection',
    }

    return len(fields)


def load_json_as_kv_lines(json_str):
    claim = json.loads(json_str)
    claim_lines = []
    for key in claim:
        value = json.dumps(claim[key], sort_keys=True)
        claim_lines.append(f'"{key}": {value}')
    return claim_lines


def diff_revision(ref, alt):
    if alt == 'none' or not alt:
        return None, None
    claim = load_json_as_kv_lines(ref)
    revision = load_json_as_kv_lines(alt)

    all_lines = sorted(set(claim) | set(revision))

    diff = []
    for line in all_lines:
        if line in claim and line in revision:
            diff.append('    ' + line)
        elif line in claim:
            diff.append('-   ' + line)
        elif line in revision:
            diff.append('+   ' + line)
        else:
            raise AssertionError('line must be in claim or revision')
    diff = ',\n'.join(diff)
    return '```text\n{\n' + diff + '\n}\n```'


