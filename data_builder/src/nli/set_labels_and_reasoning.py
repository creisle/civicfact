def filter_row(row: dict):
    """
    Filter out any generated content that is likely to produce problematic pairs
    """
    has_ground_truth = bool(
        isinstance(row['ground_truth_row'], dict) and len(row['ground_truth_row'])
    )
    has_civic_eid = bool(not pd.isnull(row['civic.id']) and row['civic.id'] != '')
    hypothesis_nei = bool(row['hypothesis.label'] == 'NEI')
    revised = has_revisions(row)
    evidence_methods = set(row['evidence.selection_method'].split(' '))
    claim_methods = set(row['claim.source'].split(' '))

    if 'evidence-swap' in evidence_methods:
        return False
    if revised_field(row, 'evidenceDirection') and revised_field(row, 'significance'):
        return True
    if has_civic_eid:
        if not has_ground_truth:
            # unable to pair with a ground truth CIViC EID that were not generated by the neutral bot
            return True
        if hypothesis_nei or (
            row['evidence.source'] == 'civic' and row['evidence.selection_method'] == 'none'
        ):
            if revised:
                # revisions on a manually selected NEI segments or civic descriptions are likely to generate unexpected correct pairs
                return True
        if row['hypothesis.label'] == 'NEI':
            # could be a specific selection that is insufficient due to ambiguity so we could be creating a valid entry with specificity changes here
            if (
                revised
                or {'modified disease specificity', 'modified drug specificity'} & claim_methods
            ):
                return True
    elif 'netural-bot' in claim_methods:
        pass

    return False


