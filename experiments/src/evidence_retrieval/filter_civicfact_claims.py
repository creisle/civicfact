"""
Filter out data where the label is likely to change or not be accurate for all the text we have available

We start with the pre-filtered set of claims that should retain validty with access to the full text (some claim/evidence pairs are
generated by the user to specifically represent cases where retrieval should fail and are artifical NEI examples. these have been filtered out).
this is accomplished by filtering out any examples with contradictory claims (claims with multiple labels)

we also remove any claims where the evidence is from a CIVIc description and not a publication
"""

import argparse
import logging

import pandas as pd

from utils import dump_jsonl, read_jsonl


def parse_requirements(conversation):
    req_tags = set()
    if not isinstance(conversation, list):
        return ""
    for chunk in conversation:
        req_tags.update([t.split("-")[-1] for t in chunk["tags"] if t.startswith("requires-")])
    return " ".join(sorted(req_tags))


def flip_label(label):
    if label == "NEI":
        return label
    if label == "REFUTES":
        return "SUPPORTS"
    if label == "SUPPORTS":
        return "REFUTES"
    raise NotImplementedError(f"unable to flip unknown label: {label}")


def simplify_df_to_claims(df):
    df = df.drop(columns=[c for c in df.columns if c.startswith("_") or c.startswith("evidence")]).drop_duplicates(
        ["claim.flat", "document.pmid"]
    )
    return df


def add_claim_labels_count(df):
    colname = "_claim_labels"
    if colname in df.columns:
        df = df.drop(columns=[colname])
    df = df.merge(
        df.groupby(["claim.flat", "document.pmid"])
        .agg({"gold_label_name": "unique"})
        .reset_index()
        .rename(columns={"gold_label_name": colname})
    )
    return df


def v1_filter(df):

    # grab NEI entries where the supplement and/or figures are requried so the NEI should be valid even with expanded access to the text
    supp_df = df.copy()
    supp_df = supp_df[
        (supp_df["generated"] == False)
        & (~supp_df["document.content_source"].isin({"civic", "pubmed"}))
        & (~supp_df["claim.source"].fillna("").str.startswith("neutral-bot"))
    ]
    supp_df = add_claim_labels_count(supp_df)
    supp_df = supp_df[
        (supp_df["claim.req"] != "") & (supp_df["gold_label_name"] == "NEI") & (supp_df._claim_labels.str.len() < 2)
    ]
    supp_df = simplify_df_to_claims(supp_df)
    logging.info(
        f"there are {supp_df.shape[0]} unique claims where supplemental information has been shown to be required"
    )

    # keep labels on abstract-only sources. filter any NEI labels where a non-NEI label was given manually for the same claim
    nei_abstract_df = df[(df["evidence.source"] == "pubmed") & (df["generated"] == False)].copy()
    nei_abstract_df = add_claim_labels_count(nei_abstract_df)
    nei_abstract_df = nei_abstract_df[
        (nei_abstract_df["gold_label_name"] != "NEI") | (nei_abstract_df._claim_labels.str.len() == 1)
    ]
    nei_abstract_df = simplify_df_to_claims(nei_abstract_df)
    logging.info(f"there are {nei_abstract_df.shape[0]} manually curated claims from abstract-only data")

    # keep any non-nei manual claims
    manual_df = df[
        (df["generated"] == False) & (df["gold_label_name"] != "NEI") & (df["evidence.source"] != "civic")
    ].copy()
    manual_df = add_claim_labels_count(manual_df)
    manual_df["_claim_labels"] = manual_df._claim_labels.apply(lambda labels: [l for l in labels if l != "NEI"])
    manual_df = manual_df[
        manual_df._claim_labels.str.len() < 2
    ]  # do not include examples that have conflicting labels (if different parts of a paper supports/refutes the same claim)
    manual_df = simplify_df_to_claims(manual_df)
    logging.info(f"there are {manual_df.shape[0]} manually curated non-nei claims")

    # keep all modified specificity NEI claims
    mod_df = df[(df["claim.source"].str.contains("modified specificity")) & (df["gold_label_name"] == "NEI")].copy()
    mod_df = simplify_df_to_claims(mod_df)
    logging.info(
        f"there are {mod_df.shape[0]} claims generated as NEI by modification of specificity of the claim elements"
    )

    # keep all bot-generated claims
    bot_df = df[(df["claim.source"].str.contains("neutral-bot")) & (df["evidence.source"] != "civic")].copy()
    bot_df = simplify_df_to_claims(bot_df)
    logging.info(f"there are {bot_df.shape[0]} bot generated claims")

    # keep all flipped claims not from civic
    flip_df = df[
        (df["claim.source"].str.contains("flipped"))
        & (df["gold_label_name"] != "NEI")
        & (df["evidence.source"] != "civic")
    ].copy()
    flip_df = simplify_df_to_claims(flip_df)
    logging.info(
        f"there are {flip_df.shape[0]} claims generated by flipping the signifiance on non-civic evidence claims"
    )

    # keep all randomly re-paired claim/evidence pairs
    repair_df = df[df["evidence.selection_method"].str.contains("evidence-swap")].copy()

    # finally, add all the claims that were given from civic as evidence, these are lowest priotiy b/c they have the least oversight.
    # since we only want the claim part we have to fix the label too, the label right now is based on NEI of the civic description instead of putative fulltext
    civic_df = df[df["evidence.source"] == "civic"].copy()
    # only keep examples where we have access to the FT. currently base this on license != ""
    civic_df = civic_df[~civic_df["document.content_source"].fillna("").isin({"pubmed", ""})]

    civic_df["gold_label_name"] = civic_df["civic.evidenceDirection"].apply(
        lambda x: "REFUTES" if x == "DOES_NOT_SUPPORT" else "SUPPORTS"
    )
    # if the signifiance was flipped we need to modify this
    civic_df.loc[civic_df["claim.source"].str.contains("flipped"), "gold_label_name"] = civic_df[
        civic_df["claim.source"].str.contains("flipped")
    ]["gold_label_name"].apply(flip_label)
    # if the signifiance was modified we should label this back to NEI
    civic_df.loc[civic_df["claim.source"].str.contains("modified specificity"), "gold_label_name"] = "NEI"

    civic_df = simplify_df_to_claims(civic_df)
    logging.info(f"there are {civic_df.shape[0]} possible claims from civic sources")

    # now concatenate all the claims in priotiy order and keep only the first label
    df = pd.concat([supp_df, nei_abstract_df, manual_df, flip_df, mod_df, bot_df, repair_df, civic_df])
    logging.info(f"concatenated to {df.shape[0]} claims")
    df = df.drop_duplicates(["claim.flat", "document.pmid"], keep="first")
    logging.info(f"filtered duplicates to {df.shape[0]} claims")
    return df


parser = argparse.ArgumentParser()
parser.add_argument("input")
parser.add_argument("document_chunks")
parser.add_argument("output")
args = parser.parse_args()

logging.basicConfig(level=logging.INFO)

doc_df = read_jsonl(args.document_chunks).rename(columns={"license": "document.license"})
doc_df = doc_df[[c for c in doc_df.columns if c.startswith("document.")]].drop_duplicates(["document.pmid"])

df = read_jsonl(args.input)
df = df.drop(columns=[c for c in doc_df.columns if c in df.columns and c != "document.pmid"])
df = df.merge(doc_df, validate="many_to_one")
df["claim.req"] = df.conversation.apply(parse_requirements)

labels = set(df.gold_label_name.unique())

if labels == {"NEI", "SUPPORTS", "REFUTES"}:
    df = v1_filter(df)
elif labels == {"NEI", "SUPPORTS", "REVISIONS"}:
    df = df[df["evidence.source"] != "civic"]
    df = add_claim_labels_count(df)
    # drop any manual NEI claims where there is a non-NEI version
    df = df[(df._claim_labels.str.len() <= 1) | (df.gold_label_name != "NEI")]
    df = add_claim_labels_count(df)
    print(df._claim_labels.str.len().value_counts())
    print(df[df._claim_labels.str.len() > 1])
    df = simplify_df_to_claims(df)
else:
    raise NotImplementedError(f"do not have a filter setup for this combination of labels: {labels}")

for partition, part_df in df.groupby("partition"):
    logging.info(f'{partition}: {dict(part_df["gold_label_name"].value_counts())}')

assert df.gold_label_name.nunique() == 3

dump_jsonl(df.drop(columns=[c for c in df.columns if c.startswith("_")]), args.output)
